def generate_hourly_zone_history(
    zone_id: str | uuid.UUID,
    profile_name: str = "commercial_core",
    total_bays: int = 50,
    max_vehicles: int = 75,
    weeks: int = 4,
    end_time: datetime | None = None,
    seed: int = 42,
) -> list[dict[str, Any]]:
    """
    Generates hourly aggregate records for a zone across the specified number of weeks.

    Parameters:
      zone_id: Zone UUID
      profile_name: Archetype profile name ('commercial_core', 'market', 'residential', 'loading_zone')
      total_bays: Number of bays in the zone
      max_vehicles: Estimated maximum vehicle capacity in the zone
      weeks: Duration of history in weeks (default: 4 weeks = 28 days = 672 hours)
      end_time: Target end time in UTC (default: current UTC hour)
      seed: Random seed for deterministic reproducibility

    Returns:
      List of hourly aggregate records stamped with provenance: "simulated".
    """
    profile = PROFILES.get(profile_name, PROFILES["commercial_core"])
    rng = np.random.default_rng(seed)
    zid = str(uuid.UUID(str(zone_id)))

    if end_time is None:
        now = datetime.now(timezone.utc)
        end_time = now.replace(minute=0, second=0, microsecond=0)
    elif end_time.tzinfo is None:
        end_time = end_time.replace(tzinfo=timezone.utc)
    else:
        end_time = end_time.astimezone(timezone.utc)

    total_hours = weeks * 7 * 24
    start_time = end_time - timedelta(hours=total_hours)

    records: list[dict[str, Any]] = []

    for h_idx in range(total_hours):
        bucket_start = start_time + timedelta(hours=h_idx)
        bucket_end = bucket_start + timedelta(hours=1)

        # Compute synthetic occupancy fraction from profile curve
        occ_frac = occupancy_fraction(profile, bucket_start, rng)
        occ_pct = round(float(occ_frac * 100.0), 2)

        # Vehicle counts based on capacity and fraction
        base_veh = occ_frac * max_vehicles
        veh_noise = float(rng.normal(0, max(1.0, max_vehicles * 0.03)))
        vehicle_count = int(max(0, round(base_veh + veh_noise)))

        # Pedestrian counts based on profile ratio
        peds = pedestrian_level(profile, vehicle_count, rng)

        record = {
            "zone_id": zid,
            "bucket_start": bucket_start.strftime("%Y-%m-%dT%H:%M:%SZ"),
            "bucket_end": bucket_end.strftime("%Y-%m-%dT%H:%M:%SZ"),
            "interval_min": 60,
            "occupancy_pct": occ_pct,
            "vehicle_count": vehicle_count,
            "pedestrian_count": peds,
            "sample_count": 60,
            "provenance": "simulated",
            "notice": "SIMULATED DATA: generated from synthetic profiles for demonstration.",
        }
        records.append(record)

    logger.info("Generated %d hourly historical records for zone %s (%d weeks, profile=%s)", len(records), zid, weeks, profile_name)
    return records


def merge_history_records(
    existing: list[dict[str, Any]],
    incoming: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """
    Merges existing and incoming historical records without duplicate timestamps.
    Incoming records overwrite existing records sharing the identical (zone_id, bucket_start).
    """
    index: dict[tuple[str, str], dict[str, Any]] = {}
    for r in existing:
        zid = str(r.get("zone_id", ""))
        bs = str(r.get("bucket_start") or r.get("ts", ""))
        if zid and bs:
            index[(zid, bs)] = r

    for r in incoming:
        zid = str(r.get("zone_id", ""))
        bs = str(r.get("bucket_start") or r.get("ts", ""))
        if zid and bs:
            index[(zid, bs)] = r

    merged = list(index.values())
    merged.sort(key=lambda x: str(x.get("bucket_start") or x.get("ts", "")))
    return merged


def seed_zone_history_to_repository(
    zone_id: str | uuid.UUID,
    repo: Any = None,
    profile_name: str = "commercial_core",
    total_bays: int = 50,
    max_vehicles: int = 75,
    weeks: int = 4,
    end_time: datetime | None = None,
    seed: int = 42,
) -> list[dict[str, Any]]:
    """
    Generates synthetic history and seeds it into the forecast repository.
    Idempotent: avoids duplicate records when rerun for the same zone and timeframe.
    """
    records = generate_hourly_zone_history(
        zone_id=zone_id,
        profile_name=profile_name,
        total_bays=total_bays,
        max_vehicles=max_vehicles,
        weeks=weeks,
        end_time=end_time,
        seed=seed,
    )

    if repo is not None:
        if hasattr(repo, "add_zone_history"):
            repo.add_zone_history(zone_id, records)
        elif hasattr(repo, "set_zone_history"):
            repo.set_zone_history(zone_id, records)

    return records


def seed_all_zones_to_repository(
    repo: Any = None,
    zones: list[dict[str, Any]] | None = None,
    weeks: int = 4,
    end_time: datetime | None = None,
    seed: int = 42,
) -> dict[str, list[dict[str, Any]]]:
    """
    Generates and seeds synthetic history across all configured default zones.
    Idempotent across repeated executions.
    """
    target_zones = zones or DEFAULT_ZONES
    results: dict[str, list[dict[str, Any]]] = {}

    for i, z in enumerate(target_zones):
        zid = str(z["zone_id"])
        zone_seed = seed + i * 1000
        records = seed_zone_history_to_repository(
            zone_id=zid,
            repo=repo,
            profile_name=z.get("profile", "commercial_core"),
            total_bays=z.get("total_bays", 50),
            max_vehicles=z.get("max_vehicles", 75),
            weeks=weeks,
            end_time=end_time,
            seed=zone_seed,
        )
        results[zid] = records

    return results


def generate_multi_zone_history(
    zones: list[dict[str, Any]] | None = None,
    weeks: int = 4,
    end_time: datetime | None = None,
    seed: int = 42,
) -> list[dict[str, Any]]:
    """Generates synthetic history across all configured zones."""
    target_zones = zones or DEFAULT_ZONES
    all_records: list[dict[str, Any]] = []

    for i, z in enumerate(target_zones):
        zone_seed = seed + i * 1000
        records = generate_hourly_zone_history(
            zone_id=z["zone_id"],
            profile_name=z.get("profile", "commercial_core"),
            total_bays=z.get("total_bays", 50),
            max_vehicles=z.get("max_vehicles", 75),
            weeks=weeks,
            end_time=end_time,
            seed=zone_seed,
        )
        all_records.extend(records)

    return all_records


