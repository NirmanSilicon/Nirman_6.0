APP_TZ = ZoneInfo("Asia/Kolkata")


@dataclass(frozen=True)
class Peak:
    """Represents a Gaussian demand peak during the day."""

    hour: float  # Hour of day in local time (0.0 to 24.0)
    amplitude: float  # Additional occupancy contribution at peak center
    width_h: float  # Gaussian standard deviation / width in hours


@dataclass(frozen=True)
class Profile:
    """Configurable synthetic demand profile archetype."""

    name: str
    base: float  # Baseline off-peak occupancy (0.0 to 1.0)
    peaks: tuple[Peak, ...]  # Daily Gaussian peaks
    weekend_factor: float  # Multiplier applied on Saturday and Sunday
    noise_sd: float  # Standard deviation of Gaussian noise
    pedestrian_per_vehicle: float  # Ratio of pedestrians per vehicle for crowd modeling


