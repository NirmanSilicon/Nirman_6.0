def occupancy_fraction(
    profile: Profile,
    dt: datetime,
    rng: np.random.Generator | None = None,
) -> float:
    """
    Computes expected occupancy fraction x in [0.0, 1.0] for a given datetime.

    Algorithm:
      1. Converts dt to local display timezone (Asia/Kolkata).
      2. Computes local fractional hour h in [0.0, 24.0).
      3. Sums base occupancy + Gaussian peaks: sum(amp * exp(-0.5 * ((h - peak.hour)/width)^2)).
      4. Multiplies by weekend_factor if day is Saturday or Sunday.
      5. Adds Gaussian noise if rng is provided and noise_sd > 0.
      6. Clips result to [0.0, 1.0].
    """
    if dt.tzinfo is None:
        local_dt = dt.replace(tzinfo=timezone.utc).astimezone(APP_TZ)
    else:
        local_dt = dt.astimezone(APP_TZ)

    h = local_dt.hour + (local_dt.minute / 60.0) + (local_dt.second / 3600.0)

    # Base + Gaussian peaks
    x = profile.base + sum(
        p.amplitude * math.exp(-0.5 * ((h - p.hour) / p.width_h) ** 2)
        for p in profile.peaks
    )

    # Weekend modulation (Saturday=5, Sunday=6)
    if local_dt.weekday() >= 5:
        x *= profile.weekend_factor

    # Gaussian noise perturbation
    if rng is not None and profile.noise_sd > 0.0:
        x += float(rng.normal(0.0, profile.noise_sd))

    return float(np.clip(x, 0.0, 1.0))


def pedestrian_level(
    profile: Profile,
    vehicles: int,
    rng: np.random.Generator | None = None,
) -> int:
    """
    Computes synthetic pedestrian count based on vehicle count and profile ratio.
    Kept strictly separate from vehicle counts per specification Module 4.1.
    """
    if vehicles <= 0:
        return 0

    noise = 0.0
    if rng is not None:
        scale = max(1.0, vehicles * 0.1)
        noise = float(rng.normal(0.0, scale))

    raw_pedestrians = round(vehicles * profile.pedestrian_per_vehicle + noise)
    return max(0, int(raw_pedestrians))


def step_bay_states(
    current_states: dict[str, str],
    target_fraction: float,
    bay_ids: list[str | uuid.UUID],
    rng: np.random.Generator,
    turnover_prob: float = 0.05,
) -> dict[str, str]:
    """
    Updates bay states toward target_fraction occupancy.

    Ensures realistic, sparse transitions by only toggling the minimum necessary bays.
    Selection among eligible candidates is deterministic for a given rng generator.
    """
    str_bay_ids = sorted(str(bid) for bid in bay_ids)
    if not str_bay_ids:
        return {}

    updated = {bid: current_states.get(bid, "free") for bid in str_bay_ids}
    n_bays = len(str_bay_ids)
    target_k = int(round(np.clip(target_fraction, 0.0, 1.0) * n_bays))

    occupied_bays = [bid for bid in str_bay_ids if updated[bid] == "occupied"]
    free_bays = [bid for bid in str_bay_ids if updated[bid] != "occupied"]
    current_k = len(occupied_bays)

    if current_k < target_k:
        # Increase occupancy: transition (target_k - current_k) free bays to occupied
        needed = target_k - current_k
        chosen = rng.choice(free_bays, size=needed, replace=False)
        for bid in chosen:
            updated[str(bid)] = "occupied"
    elif current_k > target_k:
        # Decrease occupancy: transition (current_k - target_k) occupied bays to free
        needed = current_k - target_k
        chosen = rng.choice(occupied_bays, size=needed, replace=False)
        for bid in chosen:
            updated[str(bid)] = "free"
    else:
        # At equilibrium: apply slight turnover if turnover_prob > 0 and mixed occupancy
        if 0 < current_k < n_bays and turnover_prob > 0.0:
            if float(rng.uniform(0.0, 1.0)) < turnover_prob:
                leaving = str(rng.choice(occupied_bays))
                arriving = str(rng.choice(free_bays))
                updated[leaving] = "free"
                updated[arriving] = "occupied"

    return updated


def generate_occupancy_message(
    camera_id: str | uuid.UUID,
    bay_states: dict[str, str] | list[dict[str, Any]],
    ts: datetime | None = None,
    msg_id: str | uuid.UUID | None = None,
    confidence: float = 1.0,
) -> dict[str, Any]:
    """
    Constructs a schema-valid OccupancyMessage payload matching the ParkSMART
    telemetry contract:
      - schema_version: 1 (int)
      - msg_id: UUID string
      - ts: ISO 8601 UTC string ending in 'Z'
      - camera_id: UUID string
      - bays: list of BayReading dicts (bay_id, state, confidence)
    """
    if ts is None:
        ts = datetime.now(timezone.utc)
    elif ts.tzinfo is None:
        ts = ts.replace(tzinfo=timezone.utc)
    else:
        ts = ts.astimezone(timezone.utc)

    iso_ts = ts.strftime("%Y-%m-%dT%H:%M:%SZ")
    message_id = str(uuid.UUID(str(msg_id)) if msg_id else uuid.uuid4())
    cam_id = str(uuid.UUID(str(camera_id)))

    bays_list: list[dict[str, Any]] = []
    if isinstance(bay_states, dict):
        for bid, state in sorted(bay_states.items(), key=lambda x: str(x[0])):
            bays_list.append({
                "bay_id": str(uuid.UUID(str(bid))),
                "state": state if state in ("occupied", "free", "unknown") else "unknown",
                "confidence": round(float(np.clip(confidence, 0.0, 1.0)), 4),
            })
    elif isinstance(bay_states, list):
        for item in bay_states:
            bays_list.append({
                "bay_id": str(uuid.UUID(str(item["bay_id"]))),
                "state": item.get("state", "free")
                if item.get("state") in ("occupied", "free", "unknown")
                else "unknown",
                "confidence": round(
                    float(np.clip(item.get("confidence", confidence), 0.0, 1.0)), 4
                ),
            })

    if not bays_list:
        raise ValueError("OccupancyMessage requires at least one bay reading (1..200).")
    if len(bays_list) > 200:
        raise ValueError(
            f"OccupancyMessage bays list exceeds maximum allowed of 200 (got {len(bays_list)})."
        )

    # Verify uniqueness of bay_id
    seen_bays = set()
    for b in bays_list:
        bid = b["bay_id"]
        if bid in seen_bays:
            raise ValueError(f"Duplicate bay_id detected in OccupancyMessage: {bid}")
        seen_bays.add(bid)

    return {
        "schema_version": 1,
        "msg_id": message_id,
        "ts": iso_ts,
        "camera_id": cam_id,
        "bays": bays_list,
    }


def split_vehicle_categories(
    total_vehicles: int,
    rng: np.random.Generator | None = None,
) -> dict[str, int]:
    """
    Splits total vehicle count into categorical shares (car, two_wheeler, bus, truck, van)
    reflecting urban traffic, ensuring sum(shares) <= total_vehicles.
    """
    if total_vehicles <= 0:
        return {
            "car": 0,
            "two_wheeler": 0,
            "bus": 0,
            "truck": 0,
            "van": 0,
        }

    probs = np.array([0.50, 0.35, 0.05, 0.05, 0.05])
    if rng is not None:
        counts = rng.multinomial(total_vehicles, probs)
    else:
        counts = [int(round(total_vehicles * p)) for p in probs]
        diff = total_vehicles - sum(counts)
        counts[0] += diff

    return {
        "car": int(counts[0]),
        "two_wheeler": int(counts[1]),
        "bus": int(counts[2]),
        "truck": int(counts[3]),
        "van": int(counts[4]),
    }


def generate_crowd_message(
    camera_id: str | uuid.UUID,
    interval_s: int,
    vehicle_count: int,
    vehicle_by_category: dict[str, int] | None = None,
    pedestrian_count: int = 0,
    density_per_m2: float | None = None,
    quality: str = "ok",
    ts: datetime | None = None,
    msg_id: str | uuid.UUID | None = None,
) -> dict[str, Any]:
    """
    Constructs a schema-valid CrowdMessage payload matching the ParkSMART telemetry contract.
    """
    if ts is None:
        ts = datetime.now(timezone.utc)
    elif ts.tzinfo is None:
        ts = ts.replace(tzinfo=timezone.utc)
    else:
        ts = ts.astimezone(timezone.utc)

    iso_ts = ts.strftime("%Y-%m-%dT%H:%M:%SZ")
    message_id = str(uuid.UUID(str(msg_id)) if msg_id else uuid.uuid4())
    cam_id = str(uuid.UUID(str(camera_id)))

    if vehicle_by_category is None:
        vehicle_by_category = split_vehicle_categories(vehicle_count)

    return {
        "schema_version": 1,
        "msg_id": message_id,
        "ts": iso_ts,
        "camera_id": cam_id,
        "interval_s": int(interval_s),
        "vehicle_count": max(0, int(vehicle_count)),
        "vehicle_by_category": vehicle_by_category,
        "pedestrian_count": max(0, int(pedestrian_count)),
        "density_per_m2": round(float(density_per_m2), 4)
        if density_per_m2 is not None
        else None,
        "quality": quality if quality in ("ok", "degraded", "suspect") else "ok",
    }


def generate_health_message(
    camera_id: str | uuid.UUID,
    state: str = "online",
    fps: float | None = 15.0,
    errors: list[str] | None = None,
    model_version: str | None = "yolo26n",
    uptime_s: int | None = None,
    ts: datetime | None = None,
    msg_id: str | uuid.UUID | None = None,
) -> dict[str, Any]:
    """
    Constructs a schema-valid HealthMessage payload matching the ParkSMART telemetry contract.
    """
    if ts is None:
        ts = datetime.now(timezone.utc)
    elif ts.tzinfo is None:
        ts = ts.replace(tzinfo=timezone.utc)
    else:
        ts = ts.astimezone(timezone.utc)

    iso_ts = ts.strftime("%Y-%m-%dT%H:%M:%SZ")
    message_id = str(uuid.UUID(str(msg_id)) if msg_id else uuid.uuid4())
    cam_id = str(uuid.UUID(str(camera_id)))

    clean_errors = [str(e)[:200] for e in (errors or [])][:20]

    return {
        "schema_version": 1,
        "msg_id": message_id,
        "ts": iso_ts,
        "camera_id": cam_id,
        "state": state if state in ("online", "degraded", "offline") else "online",
        "fps": round(float(fps), 2) if fps is not None else None,
        "errors": clean_errors,
        "model_version": model_version,
        "uptime_s": max(0, int(uptime_s)) if uptime_s is not None else None,
    }
