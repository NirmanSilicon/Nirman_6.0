// Helper to filter start locations by text search (matches city, state, country, hub name, category)
export function matchesStartLocationSearch(location: CityStartLocation, query: string): boolean {
  if (!query.trim()) return true;
  const q = query.toLowerCase().trim();
  return (
    location.name.toLowerCase().includes(q) ||
    location.cityName.toLowerCase().includes(q) ||
    (location.state ? location.state.toLowerCase().includes(q) : false) ||
    location.country.toLowerCase().includes(q) ||
    location.category.toLowerCase().includes(q) ||
    location.region.toLowerCase().includes(q) ||
    location.prmFacilities.some((f) => f.toLowerCase().includes(q))
  );
}

// Helper to get unique city names with counts
export function getUniqueStartCities(locations: CityStartLocation[] = ALL_START_LOCATIONS): { cityName: string; country: string; state?: string; count: number }[] {
  const map = new Map<string, { cityName: string; country: string; state?: string; count: number }>();
  locations.forEach((loc) => {
    const key = `${loc.cityName}__${loc.country}`;
    if (!map.has(key)) {
      map.set(key, { cityName: loc.cityName, country: loc.country, state: loc.state, count: 1 });
    } else {
      map.get(key)!.count += 1;
    }
  });
  return Array.from(map.values()).sort((a, b) => a.cityName.localeCompare(b.cityName));
}

