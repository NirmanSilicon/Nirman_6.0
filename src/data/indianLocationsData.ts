// Helper to search and filter Indian locations
export function matchesIndianLocationSearch(loc: IndianLocation, query: string): boolean {
  if (!query.trim()) return true;
  const q = query.toLowerCase().trim();
  return (
    loc.name.toLowerCase().includes(q) ||
    loc.district.toLowerCase().includes(q) ||
    loc.state.toLowerCase().includes(q) ||
    loc.type.toLowerCase().includes(q) ||
    loc.famousLandmark.toLowerCase().includes(q) ||
    loc.region.toLowerCase().includes(q) ||
    (loc.pincode ? loc.pincode.includes(q) : false) ||
    loc.accessibleTransit.toLowerCase().includes(q)
  );
}

// Helper to get grouped locations by State
export function getIndianLocationsByState(): Record<string, IndianLocation[]> {
  const grouped: Record<string, IndianLocation[]> = {};
  ALL_INDIAN_LOCATIONS.forEach((loc) => {
    if (!grouped[loc.state]) {
      grouped[loc.state] = [];
    }
    grouped[loc.state].push(loc);
  });
  return grouped;
}

