API_ENDPOINT = "http://127.0.0.1:8000/api/v1/telemetry"


def generate_synthetic_reading(
    device_id: str,
    step_idx: int,
    total_steps: int,
    base_ambient_temp: float = 28.0,
    base_humidity: float = 55.0,
    stress_phase: bool = False,
    sensor_fault: bool = False,
    night_phase: bool = False
) -> Dict[str, Any]:
    """Generates a physiologically plausible synthetic reading for a plant."""
    dev_meta = ACTIVE_DEVICES[device_id]
    dry_adc = dev_meta["default_soil_dry_adc"]
    wet_adc = dev_meta["default_soil_wet_adc"]

    # Diurnal solar curve (0 to 1)
    solar_factor = 0.0 if night_phase else math.sin(math.pi * (step_idx % total_steps) / total_steps)
    solar_factor = max(0.0, solar_factor)

    # Ambient conditions
    ambient_temp = round(base_ambient_temp + (4.0 * solar_factor) + random.uniform(-0.3, 0.3), 2)
    humidity = round(base_humidity - (12.0 * solar_factor) + random.uniform(-1.0, 1.0), 2)
    light_lux = 10.0 if night_phase else round(max(0.0, (15000.0 * solar_factor) + random.uniform(-300, 300)), 1)

    # Sensor fault simulation
    if sensor_fault:
        return {
            "device_id": device_id,
            "firmware_version": "1.0.0-sim",
            "readings": {
                "soil_moisture_raw": 0,  # Invalid ADC fault
                "soil_moisture_pct": 0.0,
                "leaf_temp_c": -99.0,
                "ambient_temp_c": ambient_temp,
                "ambient_humidity_pct": humidity,
                "light_lux": light_lux
            },
            "diagnostics": {
                "wifi_rssi": -70,
                "mlx_connected": False,  # Fault flag
                "aht_connected": True,
                "bh1750_connected": True,
                "soil_sensor_valid": False,
                "uptime_seconds": 1200
            },
            "is_simulated": True
        }

    # Plant-specific transpirational behavior
    if device_id == "TULSI_01":
        # Well-watered condition: soil moisture ~55%
        soil_pct = round(55.0 + random.uniform(-2.0, 2.0), 1)
        raw_adc = int(dry_adc - (soil_pct / 100.0) * (dry_adc - wet_adc))
        # Leaf cooler than air due to transpiration
        leaf_temp = round(ambient_temp - (1.8 * solar_factor) + random.uniform(-0.2, 0.2), 2)

    elif device_id == "HIBISCUS_01":
        if stress_phase:
            # Water stress: dry soil ~24% (below 40% threshold)
            soil_pct = round(24.0 - (step_idx * 0.1) + random.uniform(-0.5, 0.5), 1)
            raw_adc = int(dry_adc - (soil_pct / 100.0) * (dry_adc - wet_adc))
            # Stomata closed: leaf warmer than air by +2.5°C to +3.5°C
            leaf_temp = round(ambient_temp + (2.5 * solar_factor) + 1.2 + random.uniform(-0.2, 0.2), 2)
        else:
            # Baseline well-watered: soil ~50%
            soil_pct = round(52.0 + random.uniform(-1.5, 1.5), 1)
            raw_adc = int(dry_adc - (soil_pct / 100.0) * (dry_adc - wet_adc))
            leaf_temp = round(ambient_temp - (1.5 * solar_factor) + random.uniform(-0.2, 0.2), 2)

    else:  # MONEYPLANT_01
        # Moderate soil moisture, healthy baseline
        soil_pct = round(45.0 + random.uniform(-1.0, 1.0), 1)
        raw_adc = int(dry_adc - (soil_pct / 100.0) * (dry_adc - wet_adc))
        leaf_temp = round(ambient_temp - (1.2 * solar_factor) + random.uniform(-0.2, 0.2), 2)

    return {
        "device_id": device_id,
        "firmware_version": "1.0.0-sim",
        "readings": {
            "soil_moisture_raw": raw_adc,
            "soil_moisture_pct": soil_pct,
            "leaf_temp_c": leaf_temp,
            "ambient_temp_c": ambient_temp,
            "ambient_humidity_pct": humidity,
            "light_lux": light_lux
        },
        "diagnostics": {
            "wifi_rssi": -65,
            "mlx_connected": True,
            "aht_connected": True,
            "bh1750_connected": True,
            "soil_sensor_valid": True,
            "uptime_seconds": 3600 + (step_idx * 300)
        },
        "is_simulated": True
    }


def seed_database_with_test_cycles(samples_per_plant: int = 35):
    """
    Directly seeds the database with calibrated simulated cycles for all 3 plants:
    - First trains a well-watered baseline Random Forest model for each plant.
    - Then generates realistic chronological cycles:
        * TULSI_01: Normal well-watered functioning.
        * HIBISCUS_01: Develops persistent water stress with canopy thermal elevation.
        * MONEYPLANT_01: Includes healthy cycles and low-light / fault cycles (testing Inconclusive).
    All records are tagged with `is_simulated = True`.
    """
    print("=" * 70)
    print("ROOTWHISPER SIMULATED DATASET GENERATOR")
    print("NOTICE: Data generated is strictly simulated (is_simulated=True).")
    print("=" * 70)

    Base.metadata.create_all(bind=engine)
    db = SessionLocal()

    try:
        # 1. Ensure devices exist
        for dev_id, meta in ACTIVE_DEVICES.items():
            dev = db.query(Device).filter(Device.device_id == dev_id).first()
            if not dev:
                dev = Device(
                    device_id=dev_id,
                    plant_name=meta["plant_name"],
                    species=meta["species"],
                    description=meta["description"],
                    soil_dry_adc=meta["default_soil_dry_adc"],
                    soil_wet_adc=meta["default_soil_wet_adc"],
                    provisional_soil_dry_threshold_pct=meta["provisional_soil_dry_threshold_pct"],
                    provisional_temp_residual_threshold_c=meta["provisional_temp_residual_threshold_c"],
                )
                db.add(dev)
        db.commit()

        # 2. Generate and train baseline models for each plant using 25 well-watered daytime samples
        print("[1/3] Generating well-watered baseline calibration datasets...")
        for dev_id in ACTIVE_DEVICES.keys():
            baseline_records = []
            for i in range(25):
                raw = generate_synthetic_reading(
                    device_id=dev_id,
                    step_idx=i,
                    total_steps=25,
                    base_ambient_temp=random.uniform(25.0, 29.0),
                    base_humidity=random.uniform(50.0, 65.0),
                    stress_phase=False,
                    night_phase=False
                )
                amb_t = raw["readings"]["ambient_temp_c"]
                rh = raw["readings"]["ambient_humidity_pct"]
                lux = raw["readings"]["light_lux"]
                vpd = calculate_vpd_kpa(amb_t, rh)
                baseline_records.append({
                    "ambient_temp_c": amb_t,
                    "ambient_humidity_pct": rh,
                    "light_lux": lux,
                    "vpd_kpa": vpd,
                    "leaf_temp_c": raw["readings"]["leaf_temp_c"]
                })
            
            metrics = train_plant_baseline(device_id=dev_id, records=baseline_records)
            print(f"  -> Model trained for {dev_id}: R2 = {metrics['r2_score']}, MAE = {metrics['mae_score']}°C")

        # 3. Generate chronological historical time-series
        print("\n[2/3] Simulating multi-cycle operational telemetry (5-minute intervals)...")
        now = datetime.now(timezone.utc)
        start_time = now - timedelta(minutes=samples_per_plant * 5)

        for dev_id in ["TULSI_01", "HIBISCUS_01", "MONEYPLANT_01"]:
            device = db.query(Device).filter(Device.device_id == dev_id).first()
            print(f"\nSimulating {samples_per_plant} cycles for {dev_id} ({device.plant_name})...")

            for step in range(samples_per_plant):
                t_timestamp = start_time + timedelta(minutes=step * 5)
                
                # Determine behavioral scenarios
                is_stress = (dev_id == "HIBISCUS_01" and step >= 15)  # Hibiscus dries out after step 15
                is_fault = (dev_id == "MONEYPLANT_01" and step in [28, 29])
                is_night = (step < 5)  # Early morning dawn / dark

                payload_dict = generate_synthetic_reading(
                    device_id=dev_id,
                    step_idx=step,
                    total_steps=samples_per_plant,
                    stress_phase=is_stress,
                    sensor_fault=is_fault,
                    night_phase=is_night
                )

                req = TelemetryIngestRequest(
                    device_id=dev_id,
                    firmware_version="1.0.0-sim",
                    readings=SensorReadingsPayload(**payload_dict["readings"]),
                    diagnostics=SensorDiagnosticsPayload(**payload_dict["diagnostics"]),
                    is_simulated=True
                )

                # Validate
                q_status, q_issues, calibrated_soil = validate_telemetry_payload(req, device)
                vpd = calculate_vpd_kpa(req.readings.ambient_temp_c, req.readings.ambient_humidity_pct)
                delta_t = calculate_delta_t_c(req.readings.leaf_temp_c, req.readings.ambient_temp_c)

                # Save telemetry
                tele = Telemetry(
                    device_id=dev_id,
                    timestamp=t_timestamp,
                    soil_moisture_raw=req.readings.soil_moisture_raw,
                    soil_moisture_pct=calibrated_soil,
                    leaf_temp_c=req.readings.leaf_temp_c,
                    ambient_temp_c=req.readings.ambient_temp_c,
                    ambient_humidity_pct=req.readings.ambient_humidity_pct,
                    light_lux=req.readings.light_lux,
                    vpd_kpa=vpd,
                    delta_t_c=delta_t,
                    wifi_rssi=req.diagnostics.wifi_rssi,
                    mlx_connected=req.diagnostics.mlx_connected,
                    aht_connected=req.diagnostics.aht_connected,
                    bh1750_connected=req.diagnostics.bh1750_connected,
                    soil_sensor_valid=req.diagnostics.soil_sensor_valid,
                    uptime_seconds=req.diagnostics.uptime_seconds,
                    quality_status=q_status,
                    quality_issues="; ".join(q_issues) if q_issues else None,
                    is_simulated=True
                )
                db.add(tele)
                db.commit()
                db.refresh(tele)

                # Run screener
                scr = evaluate_water_stress(
                    db=db,
                    device=device,
                    telemetry=tele,
                    quality_status=q_status,
                    quality_issues=q_issues
                )

            # Update device last seen
            device.last_seen = now
            device.is_online = True
            db.commit()

        print("\n[3/3] Synthetic testing dataset generated successfully!")
        print(f"Total telemetry records in DB: {db.query(Telemetry).count()}")
        print(f"Total screening results in DB: {db.query(ScreeningResult).count()}")

    finally:
        db.close()


def post_live_simulated_packet(device_id: str, stress: bool = False):
    """Sends a single live HTTP POST packet to the running FastAPI server for API testing."""
    payload = generate_synthetic_reading(
        device_id=device_id,
        step_idx=15,
        total_steps=30,
        stress_phase=stress
    )
    resp = requests.post(API_ENDPOINT, json=payload, timeout=5)
    return resp.json()


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--live":
        print(f"Sending live simulated test packet to {API_ENDPOINT} ...")
        res = post_live_simulated_packet("TULSI_01")
        print("Response:", res)
    else:
        seed_database_with_test_cycles(samples_per_plant=30)

