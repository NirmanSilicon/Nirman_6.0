      [
        'Assessment ID',
        'Date',
        'Mother ID',
        'Mother',
        'Type',
        'Recorded Risk Classification',
        'Assessor & Role (Source)',
        'Facility / Location',
      ]
        .map(escapeCsvCell)
        .join(',')
