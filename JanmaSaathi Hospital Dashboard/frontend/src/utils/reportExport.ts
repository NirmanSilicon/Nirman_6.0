/**
 * Determines patient data access restrictions for report generation & exports.
 * - Mothers are restricted from multi-patient hospital analytics exports.
 * - Health Workers are restricted to de-identified aggregate summaries only.
 * - Authorized hospital clinicians, staff, and supervisors receive consent-masked hospital access.
 */
export function getReportAccessScope(role: string): ReportAccessScope {
  const normalized = (role || '').trim().toLowerCase();
  if (!normalized || normalized === 'mother' || normalized.includes('patient')) {
    return 'denied';
  }
  if (
    normalized === 'health worker' ||
    normalized === 'health_worker' ||
    normalized.includes('asha') ||
    normalized.includes('anm')
  ) {
    return 'aggregate-only';
  }
  const authorizedKeywords = [
    'hospital',
    'doctor',
    'ob-gyn',
    'medical officer',
    'clinician',
    'nurse',
    'admin',
    'supervisor',
    'triage',
    'superintendent',
    'staff',
  ];
  if (authorizedKeywords.some((k) => normalized.includes(k))) {
    return 'full-hospital';
  }
  return 'aggregate-only';
}

/**
 * Escapes a CSV cell and neutralizes spreadsheet formula injection (=, +, -, @, tab, CR).
 */
export function escapeCsvCell(value: string): string {
  const str = String(value ?? '');
  const trimmedLeading = str.replace(/^[\s]+/, '');
  const needsFormulaGuard =
    /^[=+\-@\t\r]/.test(str) || /^[=+\-@]/.test(trimmedLeading);
  const guarded = needsFormulaGuard ? `'${str}` : str;
  return `"${guarded.replace(/"/g, '""')}"`;
}

function triggerFileDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

function maskPatientName(
  fullName: string,
  motherId: string,
  deidentify: boolean
): string {
  if (!deidentify) return fullName;
  return `Patient (${motherId})`;
}

/**
 * Exports a single structured table report as CSV with metadata header & formula-injection guard.
 */
export function exportTableCsv(params: {
  filename: string;
  reportTitle: string;
  facilityName: string;
  modeLabel: string;
  dateRangeLabel: string;
  generatedBy: string;
  accessScopeLabel: string;
  headers: string[];
  rows: string[][];
}): void {
  const generatedAt = new Date().toISOString().slice(0, 19).replace('T', ' ');
  const csvLines = [
    [
      'JanmaSaathi Hospital Dashboard Report',
      params.reportTitle,
      params.facilityName,
      params.modeLabel,
    ]
      .map(escapeCsvCell)
      .join(','),
    [
      `Date Range: ${params.dateRangeLabel}`,
      `Generated By: ${params.generatedBy}`,
      `Generated At: ${generatedAt} UTC`,
      `Access Scope: ${params.accessScopeLabel}`,
    ]
      .map(escapeCsvCell)
      .join(','),
    escapeCsvCell(
      'Governance Note: Analytics summarize recorded JanmaSaathi data and do not constitute medical diagnosis.'
    ),
    '',
    params.headers.map(escapeCsvCell).join(','),
    ...params.rows.map((row) => row.map(escapeCsvCell).join(',')),
  ];

  const blob = new Blob([csvLines.join('\n')], {
    type: 'text/csv;charset=utf-8;',
  });
  triggerFileDownload(blob, params.filename);
}

